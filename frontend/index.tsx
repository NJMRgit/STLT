import { ChromeDevToolsProtocol, definePlugin, DialogButton, Field, Toggle, pluginConfig, usePluginConfig } from 'millennium';

const LOG = 'frontend';
const ENABLED_KEY = 'native-enabled';
const AUTO_KEY = 'auto-apply';
const FLAG_COMPOSITED = 256;
const FLAG_TRANSPARENT_PARENT = 1 << 22; // 4194304
const LAST_RESTART_KEY = 'sl-transparency-last-restart';
const BP_KEY = 'sl-transparency-in-bigpicture';
const SAVED_DETAILS_KEY = 'sl-transparency-desktop-details';
const MIN_WIDTH = 1010;
const MIN_HEIGHT = 600;

const state = {
	enabled: true,
	autoApply: true,
	busy: false,
};

async function log(msg: string) {
	try {
		// @ts-ignore generated by starlight
		await backend.log_from_frontend(`[${LOG}] ${msg}`);
	} catch (e) {
		console.log('steam-linux-transparency:', msg);
	}
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function steamGlobal(): any {
	return globalThis as any;
}

async function getMainWindowFlags(): Promise<number | null> {
	try {
		const res: any = await ChromeDevToolsProtocol.send('Target.getTargets');
		const target = (res?.targetInfos ?? []).find((t: any) => t.type === 'page' && t.title === 'Steam');
		if (!target?.url) return null;
		const match = /[?&]createflags=(\d+)/.exec(target.url);
		return match ? parseInt(match[1], 10) : null;
	} catch {
		return null;
	}
}

async function restartUi(): Promise<boolean> {
	try {
		const browser = steamGlobal().SteamClient?.Browser;
		if (browser?.RestartJSContext) {
			browser.RestartJSContext();
			return true;
		}
	} catch {}

	// Fallback: call it from the main window's main world.
	try {
		const targets: any = await ChromeDevToolsProtocol.send('Target.getTargets');
		const steam = (targets?.targetInfos ?? []).find((t: any) => t.type === 'page' && t.title === 'Steam');
		if (!steam) return false;
		const attached: any = await ChromeDevToolsProtocol.send('Target.attachToTarget', {
			targetId: steam.targetId,
			flatten: true,
		});
		await ChromeDevToolsProtocol.send(
			'Runtime.evaluate',
			{ expression: 'SteamClient.Browser.RestartJSContext()', returnByValue: true } as any,
			attached.sessionId,
		);
		return true;
	} catch {
		return false;
	}
}

async function attachMainTarget(): Promise<{ target: any; sessionId: string } | null> {
	try {
		const res: any = await ChromeDevToolsProtocol.send('Target.getTargets');
		const target = (res?.targetInfos ?? []).find((t: any) => t.type === 'page' && t.title === 'Steam');
		if (!target) return null;
		const attached: any = await ChromeDevToolsProtocol.send('Target.attachToTarget', {
			targetId: target.targetId,
			flatten: true,
		});
		if (!attached?.sessionId) return null;
		return { target, sessionId: attached.sessionId };
	} catch {
		return null;
	}
}

async function setMainWindowMinSize(): Promise<boolean> {
	const main = await attachMainTarget();
	if (!main) return false;
	try {
		await ChromeDevToolsProtocol.send(
			'Runtime.evaluate',
			{ expression: `SteamClient.Window.SetMinSize(${MIN_WIDTH},${MIN_HEIGHT})`, returnByValue: true } as any,
			main.sessionId,
		);
		return true;
	} catch {
		return false;
	} finally {
		try {
			await ChromeDevToolsProtocol.send('Target.detachFromTarget', { sessionId: main.sessionId });
		} catch {}
	}
}

async function getMainWindowRestoreDetails(): Promise<string | null> {
	const main = await attachMainTarget();
	if (!main) return null;
	try {
		const res: any = await ChromeDevToolsProtocol.send(
			'Runtime.evaluate',
			{ expression: 'SteamClient.Window.GetWindowRestoreDetails()', returnByValue: true } as any,
			main.sessionId,
		);
		const value = res?.result?.value ?? res?.result?.result?.value ?? res?.value ?? null;
		return typeof value === 'string' ? value : null;
	} catch {
		return null;
	} finally {
		try {
			await ChromeDevToolsProtocol.send('Target.detachFromTarget', { sessionId: main.sessionId });
		} catch {}
	}
}

async function restoreMainWindowSize(): Promise<boolean> {
	const main = await attachMainTarget();
	if (!main) return false;
	try {
		let details = localStorage.getItem(SAVED_DETAILS_KEY);
		if (!details) {
			const url = new URL(main.target.url);
			const x = url.searchParams.get('x');
			const y = url.searchParams.get('y');
			const w = url.searchParams.get('w');
			const h = url.searchParams.get('h');
			if (!x || !y || !w || !h) return false;
			details = `1&x=${x}&y=${y}&w=${w}&h=${h}`;
		}
		await ChromeDevToolsProtocol.send(
			'Runtime.evaluate',
			{ expression: `SteamClient.Window.RestoreWindowSizeAndPosition(${JSON.stringify(details)})`, returnByValue: true } as any,
			main.sessionId,
		);
		return true;
	} catch {
		return false;
	} finally {
		try {
			await ChromeDevToolsProtocol.send('Target.detachFromTarget', { sessionId: main.sessionId });
		} catch {}
	}
}

let minSizeTimer: any = null;

async function enforceMinSizeAfterBigPicture(): Promise<void> {
	if (!state.enabled) return;

	let mode: number | null = null;
	try {
		mode = steamGlobal().SteamClient?.UI?.GetUIMode?.() ?? null;
	} catch {}

	if (mode === 4) {
		localStorage.setItem(BP_KEY, '1');
		return;
	}
	if (mode !== null && mode !== 7) return;

	const bp = localStorage.getItem(BP_KEY) === '1';

	if (!bp) {
		const details = await getMainWindowRestoreDetails();
		if (details) localStorage.setItem(SAVED_DETAILS_KEY, details);
	}

	await setMainWindowMinSize();

	if (bp) {
		// Let the desktop window finish resizing before restoring the saved size.
		await sleep(150);
		await setMainWindowMinSize();
		const restored = await restoreMainWindowSize();
		if (restored) {
			localStorage.removeItem(BP_KEY);
			await log('big picture exit: min size and window size restored');
		}
	}
}

function startMinSizeWatch() {
	try {
		steamGlobal().SteamClient?.UI?.RegisterForUIModeChanged?.((mode: number) => {
			if (mode === 4) localStorage.setItem(BP_KEY, '1');
			if (mode === 7) {
				setTimeout(() => enforceMinSizeAfterBigPicture().catch(() => {}), 300);
				setTimeout(() => enforceMinSizeAfterBigPicture().catch(() => {}), 1500);
			}
		});
	} catch {}

	// The sp.js desktop effect handles Big Picture exit retries itself.
	// Avoid a continuous CDP attach/evaluate loop, which can destabilize CEF.
	setTimeout(() => {
		enforceMinSizeAfterBigPicture().catch(() => {});
	}, 1000);

	if (diskPatchTimer) clearInterval(diskPatchTimer);
	diskPatchTimer = setInterval(() => {
		watchDiskPatch().catch(() => {});
	}, 10000);
	setTimeout(() => {
		watchDiskPatch().catch(() => {});
	}, 3000);
}

async function apply(force = false): Promise<boolean> {
	if (state.busy) return false;
	state.busy = true;
	try {
		if (!state.enabled) {
			if (force) {
				try {
					// @ts-ignore generated by starlight
					const restored = await backend.restore_sp_patch();
					await log('restore: ' + restored);
				} catch (e) {
					await log('restore failed: ' + String(e));
				}
				return await restartUi();
			}
			return true;
		}

		const flags = await getMainWindowFlags();
		if (!force && flags !== null && (flags & FLAG_TRANSPARENT_PARENT) !== 0) {
			return true;
		}

		try {
			// @ts-ignore generated by starlight
			const patched = await backend.ensure_sp_patch();
			await log(`apply patch=${patched} flags=${flags}`);
		} catch (e) {
			// The sp.js patch may still be on disk from an earlier run; a reload
			// is still worth trying if the backend is temporarily unavailable.
			await log(`apply backend unavailable flags=${flags}: ${String(e)}`);
		}

		const last = Number(localStorage.getItem(LAST_RESTART_KEY) || 0);
		if (!force && Date.now() - last < 10000) {
			await log('apply: restart cooldown');
			return false;
		}
		localStorage.setItem(LAST_RESTART_KEY, String(Date.now()));
		await log('apply: restarting Steam UI');
		return await restartUi();
	} finally {
		state.busy = false;
	}
}

async function autoApply() {
	if (!state.enabled || !state.autoApply) return;
	if (!steamGlobal().SteamClient?.UI) return;

	for (let i = 0; i < 40; i++) {
		const flags = await getMainWindowFlags();
		if (flags !== null) {
			await apply(false);
			return;
		}
		await sleep(500);
	}
	await log('auto: Steam target not found');
}

function applyMenuAttributes(popup: any) {
	try {
		if (!popup?.GetName?.().startsWith('contextmenu_')) return;
		const root = popup.window?.document?.documentElement;
		if (!root) {
			setTimeout(() => applyMenuAttributes(popup), 50);
			return;
		}
		root.setAttribute('createflags', 'Resizable Composited TransparentParentWindow');
	} catch {}
}

let menuPopupHandle: any = null;

function registerMenuPopupHook() {
	try {
		const pm = (globalThis as any).g_PopupManager ?? (globalThis as any).window?.g_PopupManager;
		if (!pm) return;
		for (const popup of Array.from((pm.GetPopups?.() ?? []) as Iterable<any>)) {
			applyMenuAttributes(popup);
		}
		menuPopupHandle = pm.AddPopupCreatedCallback(applyMenuAttributes);
	} catch {}
}

let diskPatchTimer: any = null;

async function watchDiskPatch() {
	if (!state.enabled) return;
	try {
		const status = await backend.ensure_sp_patch();
		if (status === 'patched') {
			await log('disk patch restored; reloading UI');
			await restartUi();
		}
	} catch {}
}

async function restartSteam() {
	try {
		const ok = await (globalThis as any).backend?.schedule_steam_restart?.();
		if (ok) {
			try {
				steamGlobal().SteamClient?.User?.StartShutdown?.(false);
			} catch {}
		}
	} catch {}
}

const Settings = () => {
	const [enabled, setEnabled] = usePluginConfig<boolean>(ENABLED_KEY);
	const [auto, setAuto] = usePluginConfig<boolean>(AUTO_KEY);
	const enabledValue = enabled === undefined || enabled === null ? state.enabled : !!enabled;
	const autoValue = auto === undefined || auto === null ? state.autoApply : !!auto;

	return (
		<>
			<Field
				label="Native window transparency"
				description="Patches Steam's window creation flags and reloads the Steam UI once so the main window, Settings, Friends List, context menus and other popups get 32-bit ARGB surfaces. Context menus are also created as managed windows so compositor blur can apply. Themes with transparent backgrounds then show the desktop."
			>
				<Toggle
					value={enabledValue}
					onChange={async (next: boolean) => {
						state.enabled = next;
						await setEnabled(next);
						await apply(true);
					}}
				/>
			</Field>
			<Field
				label="Apply automatically on startup"
				description="Reapply after a Steam start or UI reload when transparency is missing."
			>
				<Toggle
					value={autoValue}
					onChange={async (next: boolean) => {
						state.autoApply = next;
						await setAuto(next);
					}}
				/>
			</Field>
			<Field
				label="Reapply now"
				description="Reapply the window flags and reload the Steam UI without restarting Steam."
			>
				<DialogButton onClick={() => apply(true)}>Reapply now</DialogButton>
			</Field>
			<Field
				label="Restart Steam"
				description="Restart the Steam client to restore native ARGB transparency after a Steam UI reload has made windows opaque. This closes the Steam client and relaunches it."
			>
				<DialogButton onClick={restartSteam}>Restart Steam</DialogButton>
			</Field>
		</>
	);
};

export default definePlugin(async () => {
	try {
		const stored = await pluginConfig.get<boolean>(ENABLED_KEY);
		state.enabled = stored === undefined || stored === null ? true : !!stored;
		const storedAuto = await pluginConfig.get<boolean>(AUTO_KEY);
		state.autoApply = storedAuto === undefined || storedAuto === null ? true : !!storedAuto;
	} catch {}
	await log('definePlugin enabled=' + state.enabled + ' auto=' + state.autoApply);
	registerMenuPopupHook();
	startMinSizeWatch();
	autoApply();
	return {
		title: 'Steam Linux Transparency',
		icon: null,
		content: <Settings />,
		onDismount() {
			try {
				menuPopupHandle?.Unsubscribe?.();
			} catch {}
			try {
				if (diskPatchTimer) clearInterval(diskPatchTimer);
			} catch {}
		},
	};
});
